import assert from 'node:assert/strict'
import {chromium,webkit} from 'playwright'
import {createTourFixture} from './interactive-onboarding-fixture.mjs'
const engine=process.env.IVE_QA_BROWSER||'chromium'
const browser=await(engine==='webkit'?webkit:chromium).launch()
const f=await createTourFixture(browser,{width:1440,height:960,settings:{product_tour_version:'2'},workspaces:[{id:'w',name:'junction_editor',path:'/isolated/orbit/junction_editor'}]})
const p=f.page;p.setDefaultTimeout(10000)
let fail=false,updates=[]
await f.context.route('**/api/workspaces/w',async route=>{
 if(route.request().method()!=='PUT')return route.fallback()
 const patch=route.request().postDataJSON();updates.push(patch)
 if(fail)return route.fulfill({status:500,json:{error:'Test: saving failed'}})
 Object.assign(f.data.workspaces[0],patch)
 return route.fulfill({json:f.data.workspaces[0]})
})
try{
 await p.goto('http://ive-guide.test/#board')
 await p.getByRole('button',{name:'Rename project junction_editor',exact:true}).click()
 const dialog=p.getByRole('dialog',{name:'Rename project',exact:true}),handle=dialog.locator('[data-dialog-drag-handle]')
 await dialog.waitFor();await p.waitForTimeout(250)
 const before=await dialog.boundingBox(),h=await handle.boundingBox()
 await p.mouse.move(h.x+60,h.y+25);await p.mouse.down();await p.mouse.move(h.x+230,h.y+105,{steps:12});await p.mouse.up()
 await p.waitForTimeout(250)
 const moved=await dialog.boundingBox()
 assert.ok(moved.x-before.x>150&&moved.y-before.y>60,'header moves dialog')
 await handle.focus();await p.keyboard.press('Home');await p.waitForTimeout(50)
 const centered=await dialog.boundingBox();assert.ok(Math.abs(centered.x-before.x)<2)
 // Long drag clamps all edges and leaves controls reachable.
 const hh=await handle.boundingBox();await p.mouse.move(hh.x+60,hh.y+25);await p.mouse.down();await p.mouse.move(1438,958,{steps:15});await p.mouse.up()
 await p.waitForTimeout(50)
 const bounded=await dialog.boundingBox();assert.ok(bounded.x+bounded.width<=1433&&bounded.y+bounded.height<=953)
 await p.setViewportSize({width:900,height:700});await p.waitForTimeout(100)
 const resized=await dialog.boundingBox();assert.ok(resized.x>=7&&resized.y>=7&&resized.x+resized.width<=893&&resized.y+resized.height<=693)
 const input=dialog.getByLabel('Project name',{exact:true});await input.fill('Orbit Editor')
 fail=true;await dialog.getByRole('button',{name:'Save',exact:true}).click();await dialog.getByRole('alert').waitFor();assert.equal(await input.inputValue(),'Orbit Editor')
 fail=false;await dialog.getByRole('button',{name:'Save',exact:true}).click();await dialog.waitFor({state:'hidden'})
 await p.getByRole('button',{name:'Rename project Orbit Editor',exact:true}).waitFor()
 assert.deepEqual(updates.at(-1),{name:'Orbit Editor'})
 assert.equal(f.data.workspaces[0].path,'/isolated/orbit/junction_editor')
 await p.reload();await p.getByRole('button',{name:'Rename project Orbit Editor',exact:true}).waitFor()
 await p.getByRole('button',{name:'Rename project Orbit Editor',exact:true}).click()
 await dialog.getByRole('button',{name:'Close',exact:true}).click();await dialog.waitFor({state:'hidden'})

 await p.setViewportSize({width:1440,height:960})
 await p.locator('[data-sidebar-new-chat]').click()
 await p.getByRole('dialog',{name:'New session',exact:true}).getByRole('button',{name:'Add project',exact:true}).click()
 const finder=p.getByRole('dialog',{name:'Add a project',exact:true})
 await finder.waitFor();await p.waitForTimeout(250)
 const finderStart=await finder.boundingBox(),fh=await finder.locator('[data-dialog-drag-handle]').boundingBox()
 await p.mouse.move(fh.x+80,fh.y+25);await p.mouse.down();await p.mouse.move(fh.x+140,fh.y+45,{steps:6});await p.mouse.up();await p.waitForTimeout(50)
 assert.ok((await finder.boundingBox()).x>finderStart.x+20,'project finder moves')
 await finder.getByRole('button',{name:'Close',exact:true}).click()
 await p.getByRole('dialog',{name:'New session',exact:true}).getByRole('button',{name:/Set up session/}).click()
 const setup=p.getByRole('dialog',{name:'New AI session',exact:true});await setup.waitFor();await p.waitForTimeout(250)
 const ss=await setup.boundingBox(),sh=await setup.locator('[data-dialog-drag-handle]').boundingBox()
 await p.mouse.move(sh.x+80,sh.y+25);await p.mouse.down();await p.mouse.move(sh.x+110,sh.y+35,{steps:6});await p.mouse.up();await p.waitForTimeout(50)
 assert.ok((await setup.boundingBox()).x>ss.x+15,'full session setup moves')
 await setup.getByRole('button',{name:'Cancel',exact:true}).click()
 assert.deepEqual(f.errors,[])
 console.log(JSON.stringify({engine,passed:true,drag:true,keyboard:true,boundsAndResize:true,renamePersists:true,errorRetainsDraft:true,folderUnchanged:true}))
}finally{await f.context.close();await browser.close()}
