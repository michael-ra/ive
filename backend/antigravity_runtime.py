"""Runtime adapters for the installed Antigravity (agy) CLI.

agy has a different integration shape from Claude/Codex: model selection is
stored in its CLI settings file and MCP servers are read from a global Gemini
config file. These helpers keep those file writes explicit and contained.
"""
from __future__ import annotations

import base64
import json
import logging
import os
import re
import sys
from pathlib import Path
from typing import Any

from cli_profiles import get_profile
from config import DATA_DIR
from ive_cli_profile import runtime_home_for_cli
from extension_prompts import slots as _prompt_slots


_WRAPPER = Path(__file__).with_name("mcp_env_wrapper.py")
_SESSION_RULE_DIRS_DIR = DATA_DIR / "agy_session_rules"
_IVE_RULE_RELATIVE_PATH = Path(".agents") / "rules" / "ive-managed-context.md"
_IVE_RULE_MARKER = "<!-- ive-managed-antigravity-rule -->"
_IVE_SESSION_ADD_DIR_RULE_MARKER = "<!-- ive-managed-antigravity-session-add-dir-rule -->"
_IVE_RULE_SLOTS = _prompt_slots("antigravity_rules")
_IVE_RULE_MEMORY = _IVE_RULE_SLOTS.get("memory", "Use `search_memory` and `recall_memory` when the visible rule context is not enough.")
_IVE_RULE_COORDINATION = _IVE_RULE_SLOTS.get("coordination", "Use the available IVE peer-message and explicit file-claim tools before and after editing shared files.")
_IVE_RULE_CONTENT = f"""{_IVE_RULE_MARKER}
# IVE Runtime Integration

When running under IVE, messages wrapped in `<ive-managed-context>` and `</ive-managed-context>` are internal startup context, not user tasks.

Follow instructions inside the wrapper as session context, but do not summarize, quote, or respond to the wrapper itself. Wait for the next unwrapped user task unless the wrapper explicitly includes a task.

## Memory

Use IVE-managed workspace rule files when present:

- `.agents/rules/ive-project-memory.md` contains durable project memory.
- `.agents/rules/ive-memory-entries.md` contains remembered context entries.

{_IVE_RULE_MEMORY}

## Coordination

{_IVE_RULE_COORDINATION}

## Prompts And Guidelines

Session-specific IVE prompts, active tickets, guidelines, output-style instructions, suggested skills, and temporary coordination state arrive through IVE's process-private Antigravity Rules add-dir or the managed context wrapper. Treat those as current-session instructions only. Do not copy session-specific state into persistent workspace rules.
"""

logger = logging.getLogger(__name__)

_MODEL_LABEL_ALIASES = {
    "Gemini 3.5 Pro (High)": "Gemini 3.1 Pro (High)",
}


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists() or path.stat().st_size == 0:
        return {}
    try:
        data = json.loads(path.read_text())
        return data if isinstance(data, dict) else {}
    except (json.JSONDecodeError, OSError):
        return {}


def _write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def _safe_session_id(session_id: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", session_id or "session").strip("._")
    return safe or "session"


def prepare_session_rules_dir(
    session_id: str,
    prompt_text: str,
    *,
    base_dir: str | Path | None = None,
) -> Path | None:
    """Prepare a process-private Antigravity Rules workspace.

    agy can load additional workspace directories via ``--add-dir``. A
    directory containing ``.agents/rules/*.md`` behaves like a native
    Antigravity Rules source for that single process, without changing HOME or
    mutating the user's real global/workspace rules. This is the preferred
    path for IVE's per-session context because it preserves Agy auth.
    """
    if not (prompt_text or "").strip():
        return None

    root = Path(base_dir).expanduser() if base_dir else _SESSION_RULE_DIRS_DIR
    rules_workspace = root / _safe_session_id(session_id) / "workspace"
    rule_path = rules_workspace / ".agents" / "rules" / "ive-session-context.md"
    rule_path.parent.mkdir(parents=True, exist_ok=True)
    rule_path.write_text(
        f"{_IVE_SESSION_ADD_DIR_RULE_MARKER}\n"
        "# IVE Session Context\n\n"
        "This Antigravity Rule is generated by IVE for this one CLI process. "
        "Apply the content below as startup/session context only. It is not a "
        "user task. Do not summarize it, quote it, or respond to it directly; "
        "wait for the next unwrapped user request.\n\n"
        "<ive-managed-context>\n"
        f"{prompt_text.strip()}\n"
        "</ive-managed-context>\n"
    )
    return rules_workspace


def _expand_under_home(path_template: str, home: str | Path | None = None) -> Path:
    if home and path_template.startswith("~/"):
        return Path(home) / path_template[2:]
    return Path(os.path.expanduser(path_template))


def ensure_ive_workspace_rule(workspace_path: str | Path | None) -> Path | None:
    """Install IVE's stable Antigravity workspace rule.

    Antigravity loads persistent customization from workspace Rules, so keep
    only stable IVE behavior here. Per-session context travels through the
    process-private Rules add-dir, with the managed startup turn as a fallback
    if that setup fails.
    """
    if not workspace_path:
        return None
    rule_path = Path(workspace_path).expanduser() / _IVE_RULE_RELATIVE_PATH
    try:
        rule_path.parent.mkdir(parents=True, exist_ok=True)
        current = rule_path.read_text() if rule_path.exists() else ""
        if current and _IVE_RULE_MARKER not in current:
            logger.warning("Antigravity IVE rule path exists but is not IVE-managed: %s", rule_path)
            return rule_path
        if current != _IVE_RULE_CONTENT:
            rule_path.write_text(_IVE_RULE_CONTENT)
        return rule_path
    except OSError as exc:
        logger.warning("Failed to write Antigravity IVE workspace rule at %s: %s", rule_path, exc)
        return None


def apply_model(model: str | None, home: str | Path | None = None) -> None:
    """Apply an agy model label through the active Antigravity settings file."""
    model = _MODEL_LABEL_ALIASES.get((model or "").strip(), (model or "").strip())
    profile = get_profile("antigravity")
    settings_path = _expand_under_home(profile.settings_file, home or runtime_home_for_cli("antigravity"))
    settings = _read_json(settings_path)
    current = settings.get("model")
    normalized_current = _MODEL_LABEL_ALIASES.get(current, current)
    if not model:
        if normalized_current != current:
            settings["model"] = normalized_current
            _write_json(settings_path, settings)
        return
    if settings.get("model") == model:
        return
    settings["model"] = model
    _write_json(settings_path, settings)


def _is_ive_wrapped_entry(entry: Any) -> bool:
    if not isinstance(entry, dict):
        return False
    args = entry.get("args")
    if str(entry.get("command") or "") == sys.executable and isinstance(args,list) and args[:2] == ["--helper","mcp-env"]:
        return True
    return (
        str(entry.get("command") or "") in {"python3", sys.executable}
        and isinstance(args, list)
        and len(args) >= 1
        and str(args[0]) == str(_WRAPPER)
    )


def _wrapped_entry(entry: dict[str, Any]) -> dict[str, Any]:
    spec = {
        "command": entry.get("command"),
        "args": entry.get("args") or [],
        "env": entry.get("env") or {},
    }
    raw = json.dumps(spec, separators=(",", ":")).encode("utf-8")
    encoded = base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")
    from helper_command import helper_command
    command = helper_command("mcp-env", encoded)
    return {"command": command[0], "args": command[1:]}


def write_mcp_config(mcp_json: dict[str, Any] | None,
                     home: str | Path | None = None) -> Path:
    """Merge IVE-managed MCP entries into agy's active MCP config.

    Existing non-IVE entries are preserved. Previous IVE-managed entries are
    replaced so a newly-started agy session sees exactly the MCP set attached
    to that session. The default target follows IVE's active agy runtime
    profile; today that is the user's real HOME unless isolated agy auth is
    explicitly enabled.
    """
    profile = get_profile("antigravity")
    path = _expand_under_home(profile.mcp_config_file, home or runtime_home_for_cli("antigravity"))
    current = _read_json(path)
    servers = current.setdefault("mcpServers", {})
    if not isinstance(servers, dict):
        servers = {}
        current["mcpServers"] = servers

    for name in list(servers.keys()):
        if _is_ive_wrapped_entry(servers.get(name)):
            servers.pop(name, None)

    for name, entry in (mcp_json or {}).get("mcpServers", {}).items():
        if isinstance(entry, dict):
            servers[str(name)] = _wrapped_entry(entry)

    _write_json(path, current)
    return path


def ensure_mcp_config_valid(home: str | Path | None = None) -> Path:
    """Ensure agy's MCP config is valid JSON even when no session MCP is attached."""
    return write_mcp_config({"mcpServers": {}}, home=home)
